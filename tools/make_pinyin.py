HAN = re.compile(r"[㐀-鿿]")


def annotate(text):
    readings = [p[0] for p in pinyin(text, style=Style.TONE, heteronym=False, neutral_tone_with_five=False)]
    # pypinyin returns one entry per Han character and one per run of other text.
    out, i = [], 0
    for chunk in re.findall(r"[㐀-鿿]|[^㐀-鿿]+", text):
        if HAN.match(chunk):
            out.append(readings[i])
        else:
            out.append(None)
        i += 1
    chars = re.findall(r"[㐀-鿿]|[^㐀-鿿]+", text)
    for phrase, fix in FIXES.items():
        for m in re.finditer(re.escape(phrase), text):
            # map character offset -> chunk index
            pos, idx = 0, 0
            while pos < m.start():
                pos += len(chars[idx]); idx += 1
            for k, py in enumerate(fix):
                out[idx + k] = py
    return [[c, p] if p else [c] for c, p in zip(chars, out)]


def main():
    src = (ROOT / "stories.js").read_text(encoding="utf-8")
    result = {}
    for m in re.finditer(r'id: "([^"]+)".*?title: \{.*?zh: "([^"]+)".*?zh: \[(.*?)\]', src, re.S):
        story_id, title, body = m.groups()
        paras = json.loads("[" + body.strip().rstrip(",") + "]")
        result[story_id] = {"title": annotate(title), "text": [annotate(p) for p in paras]}
    out = "// Generated by tools/make_pinyin.py from stories.js. Do not edit by hand.\n"
    out += "// Each entry is [text] or [character, pinyin].\n"
    out += "window.PINYIN = " + json.dumps(result, ensure_ascii=False) + ";\n"
    (ROOT / "pinyin.js").write_text(out, encoding="utf-8")
    print(f"{len(result)} stories")


if __name__ == "__main__":
    main()
